-- D2: Onboarding — /start'dan keyingi xabar va savollar admin panelda (qadamma-qadam, 3 tilda).
-- O'rnatilgan (system) qadamlar o'chirilmaydi: WELCOME, CROP, IRRIGATION, WATER_SOURCE (fermer ustunlariga yoziladi), FINISH (har doim oxirida).
-- Admin qo'shgan savol javoblari — farmer_answers. Matnda {name} — fermer ismi (MessageFormat emas: ' muammosiz).
CREATE TABLE onboarding_steps (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    code              VARCHAR(32)   NOT NULL,
    position          INT           NOT NULL,
    kind              VARCHAR(16)   NOT NULL,
    target            VARCHAR(32),                       -- o'rnatilgan savol: qaysi fermer ustuniga
    texts             JSONB         NOT NULL,            -- {"uz": "...", "ru": "...", "en": "..."}
    options           JSONB,                             -- maxsus savol: [{"value": "YES", "labels": {"uz": "...", ...}}]
    system            BOOLEAN       NOT NULL DEFAULT FALSE,
    active            BOOLEAN       NOT NULL DEFAULT TRUE,
    updated_by_email  VARCHAR(120),
    created_date      TIMESTAMP(6)  NOT NULL DEFAULT now(),
    updated_date      TIMESTAMP(6)  NOT NULL DEFAULT now(),

    CONSTRAINT pk_onboarding_steps PRIMARY KEY (id),
    CONSTRAINT uk_onboarding_steps_code UNIQUE (code),
    CONSTRAINT ck_onboarding_steps_kind CHECK (kind IN ('MESSAGE', 'QUESTION')),
    CONSTRAINT ck_onboarding_steps_target CHECK (target IS NULL OR target IN ('MAIN_CROP', 'IRRIGATION_TYPE', 'WATER_SOURCE')),
    CONSTRAINT ck_onboarding_steps_code CHECK (code ~ '^[A-Z][A-Z0-9_]{1,31}$')
);

CREATE TABLE farmer_answers (
    farmer_id    BIGINT        NOT NULL,
    step_code    VARCHAR(32)   NOT NULL,
    value        VARCHAR(64)   NOT NULL,
    answered_at  TIMESTAMP(6)  NOT NULL DEFAULT now(),
    CONSTRAINT pk_farmer_answers PRIMARY KEY (farmer_id, step_code),
    CONSTRAINT fk_farmer_answers_farmer FOREIGN KEY (farmer_id) REFERENCES farmers (id)
);

