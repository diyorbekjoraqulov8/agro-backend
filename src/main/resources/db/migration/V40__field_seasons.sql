-- H1 (docs/dala-hisobi-roadmap.md): ekin mavsumi — ekish sanasi. Kalendar, GDD, hosil prognozi shunga bog'liq.
-- Alohida jadval: bitta dalada yilda bir necha ekin (bug'doydan keyin takroriy ekin) — tarix saqlanadi.
CREATE TABLE field_seasons (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    field_id       BIGINT       NOT NULL,
    crop           VARCHAR(32)  NOT NULL,
    sowing         VARCHAR(16)  NOT NULL DEFAULT 'UNANSWERED',
    sown_on        DATE,
    sown_on_approx BOOLEAN      NOT NULL DEFAULT FALSE,     -- "2–4 hafta oldin" kabi tugmadan — taxminiy sana
    status         VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    finished_on    DATE,
    created_date   TIMESTAMP(6),
    updated_date   TIMESTAMP(6),

    CONSTRAINT pk_field_seasons PRIMARY KEY (id),
    CONSTRAINT fk_field_seasons_field FOREIGN KEY (field_id) REFERENCES fields (id),
    CONSTRAINT ck_field_seasons_sowing CHECK (sowing IN ('UNANSWERED', 'SOWN', 'NOT_SOWN', 'UNKNOWN')),
    CONSTRAINT ck_field_seasons_sown_on CHECK ((sowing = 'SOWN') = (sown_on IS NOT NULL)),
    CONSTRAINT ck_field_seasons_status CHECK (status IN ('ACTIVE', 'FINISHED')),
    CONSTRAINT ck_field_seasons_finished CHECK ((status = 'FINISHED') = (finished_on IS NOT NULL))
);

-- Bitta dalada bir vaqtda faqat bitta faol mavsum (qisman index — yopilganlar tarix sifatida qoladi)
CREATE UNIQUE INDEX uq_field_seasons_active ON field_seasons (field_id) WHERE status = 'ACTIVE';
CREATE INDEX idx_field_seasons_field ON field_seasons (field_id);

-- Sug'orish usuli — har DALANIKI (bitta xo'jalikda egat ham, tomchilatib ham); boshlang'ich qiymat — fermer javobi
ALTER TABLE fields ADD COLUMN irrigation_method VARCHAR(32);
UPDATE fields f SET irrigation_method = fa.irrigation_type FROM farmers fa WHERE fa.id = f.farmer_id;

-- Mavjud dalalar: sanasi so'ralmagan faol mavsum (fermer dala kartasidan belgilaydi)
INSERT INTO field_seasons (field_id, crop, created_date, updated_date)
SELECT id, crop, now(), now() FROM fields WHERE deleted = FALSE;
