-- Tariflar. Limitlar DB'da — admin deploysiz o'zgartiradi (ADR #2 mantig'i).
-- Soft delete YO'Q: obunalar rejaga bog'langan; reja o'chirilmaydi, active = FALSE qilinadi.
CREATE TABLE plans (
    id             BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    code           VARCHAR(32)   NOT NULL,
    name           VARCHAR(80)   NOT NULL,
    description    TEXT,
    price          NUMERIC(12,2) NOT NULL DEFAULT 0,
    currency       VARCHAR(3)    NOT NULL DEFAULT 'UZS',
    duration_days  INT,                         -- NULL faqat tizim rejasi (FREE) uchun
    max_field_ha   NUMERIC(8,2)  NOT NULL,
    max_fields     INT           NOT NULL,
    max_analyses   INT,                         -- NULL — cheksiz; FREE: umrbod, pullik: davr ichida
    system_plan    BOOLEAN       NOT NULL DEFAULT FALSE,
    active         BOOLEAN       NOT NULL DEFAULT TRUE,
    created_date   TIMESTAMP(6),
    updated_date   TIMESTAMP(6),

    CONSTRAINT pk_plans PRIMARY KEY (id),
    CONSTRAINT uk_plans_code UNIQUE (code),
    CONSTRAINT ck_plans_price    CHECK (price >= 0),
    CONSTRAINT ck_plans_limits   CHECK (max_field_ha > 0 AND max_fields > 0 AND (max_analyses IS NULL OR max_analyses >= 0)),
    CONSTRAINT ck_plans_duration CHECK (system_plan OR (duration_days IS NOT NULL AND duration_days > 0))
);

-- To'lovlar tarixi. O'CHIRILMAYDI (moliyaviy yozuv) — faqat CANCELLED + sabab.
-- recorded_by — xodim id, FK yo'q (audit_logs kabi: xodim o'chsa ham tarix buzilmasin)
CREATE TABLE farmer_subscriptions (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    farmer_id          BIGINT        NOT NULL,
    plan_id            BIGINT        NOT NULL,
    status             VARCHAR(16)   NOT NULL DEFAULT 'ACTIVE',
    valid_from         DATE          NOT NULL,
    valid_until        DATE          NOT NULL,
    amount             NUMERIC(12,2) NOT NULL,
    currency           VARCHAR(3)    NOT NULL,
    paid_at            TIMESTAMP(6)  NOT NULL,
    payment_method     VARCHAR(16)   NOT NULL,
    note               TEXT,
    recorded_by_id     BIGINT,
    recorded_by_email  VARCHAR(120),
    cancelled_at       TIMESTAMP(6),
    cancel_reason      VARCHAR(500),
    created_date       TIMESTAMP(6),
    updated_date       TIMESTAMP(6),

    CONSTRAINT pk_farmer_subscriptions PRIMARY KEY (id),
    CONSTRAINT fk_subscriptions_farmer FOREIGN KEY (farmer_id) REFERENCES farmers (id),
    CONSTRAINT fk_subscriptions_plan   FOREIGN KEY (plan_id) REFERENCES plans (id),
    CONSTRAINT ck_subscriptions_status CHECK (status IN ('ACTIVE', 'CANCELLED')),
    CONSTRAINT ck_subscriptions_method CHECK (payment_method IN ('CASH', 'CARD', 'TRANSFER', 'OTHER')),
    CONSTRAINT ck_subscriptions_period CHECK (valid_from <= valid_until),
    CONSTRAINT ck_subscriptions_amount CHECK (amount >= 0)
);

CREATE INDEX idx_subscriptions_farmer   ON farmer_subscriptions (farmer_id, valid_until DESC);
CREATE INDEX idx_subscriptions_expiring ON farmer_subscriptions (valid_until) WHERE status = 'ACTIVE';

