INSERT INTO permissions (name, description) VALUES
    ('settings:read',   'Xizmat sozlamalarini ko''rish'),
    ('settings:manage', 'Xizmat sozlamalarini o''zgartirish (limitlar, chegaralar, yoqish/o''chirish)'),
    ('referral:read',   'Takliflar (referral) statistikasi')
ON CONFLICT (name) WHERE deleted = FALSE DO NOTHING;

-- ── Rollar matritsasi. Faqat QO'SHILADI (mavjud ruxsatlar olinmaydi — admin Rollar sahifasida o'zgartirgan bo'lishi mumkin)
--   ADMIN      — hammasi
--   MANAGER    — biznes: fermerlar, to'lovlar/tariflar, takliflar, statistika
--   AGRONOMIST — agronomiya: fermer/dala/tahlil (ishga tushirish ham), murojaatlar
--   OPERATOR   — qo'llab-quvvatlash: murojaatlar + javob uchun kontekst (fermer, dala, tahlil — faqat ko'rish)
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM roles r JOIN permissions p ON
    (r.name = 'ADMIN'      AND p.name IN ('settings:read', 'settings:manage', 'referral:read'))
 OR (r.name = 'MANAGER'    AND p.name IN ('farmer:read', 'farmer:update', 'field:read', 'analysis:read',
                                          'billing:read', 'billing:manage', 'referral:read', 'settings:read',
                                          'feedback:read', 'file:read'))
 OR (r.name = 'AGRONOMIST' AND p.name IN ('analysis:run', 'settings:read'))
 OR (r.name = 'OPERATOR'   AND p.name IN ('farmer:read', 'field:read', 'analysis:read'))
ON CONFLICT DO NOTHING;
