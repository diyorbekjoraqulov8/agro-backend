-- C1: admin boshqaradigan sozlamalar, "Do'stlarni taklif qilish" va xodim rollari matritsasi.

-- ── Sozlamalar (admin panel → Sozlamalar). Kalit va default'lar kodda (Setting enum), bu yerda faqat o'zgartirilgani
CREATE TABLE app_settings (
    key               VARCHAR(64)   NOT NULL,
    value             TEXT          NOT NULL,          -- tur Setting enum'ida (BOOL/INT/PLAN...)
    updated_by_email  VARCHAR(120),
    updated_date      TIMESTAMP(6)  NOT NULL DEFAULT now(),
    CONSTRAINT pk_app_settings PRIMARY KEY (key)
);

-- ── Taklif (referral): har fermerning kodi; kim taklif qilgani; "faol" — birinchi tahlili tayyor bo'lgan
ALTER TABLE farmers
    ADD COLUMN referral_code   VARCHAR(16),
    ADD COLUMN referred_by_id  BIGINT,
    ADD COLUMN referred_at     TIMESTAMP(6),
    ADD COLUMN activated_at    TIMESTAMP(6),
    ADD CONSTRAINT fk_farmers_referred_by FOREIGN KEY (referred_by_id) REFERENCES farmers (id),
    ADD CONSTRAINT ck_farmers_not_self_referred CHECK (referred_by_id IS NULL OR referred_by_id <> id);

CREATE UNIQUE INDEX uq_farmers_referral_code ON farmers (referral_code) WHERE referral_code IS NOT NULL;
CREATE INDEX idx_farmers_referred_by ON farmers (referred_by_id) WHERE referred_by_id IS NOT NULL;

-- Mavjud fermerlar: birinchi tayyor tahlil — faollashgan vaqt
UPDATE farmers fr SET activated_at = x.first_done
FROM (SELECT f.farmer_id, min(j.finished_at) AS first_done
      FROM analysis_jobs j JOIN fields f ON f.id = j.field_id
      WHERE j.status = 'DONE' GROUP BY f.farmer_id) x
WHERE fr.id = x.farmer_id;

-- Berilgan mukofotlar: har biri N ta faol do'stni "ishlatadi" (N — referral.required sozlamasi berilgan paytdagi)
CREATE TABLE referral_rewards (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    farmer_id        BIGINT        NOT NULL,
    subscription_id  BIGINT        NOT NULL,
    referrals_used   INT           NOT NULL,
    created_date     TIMESTAMP(6)  NOT NULL DEFAULT now(),
    CONSTRAINT pk_referral_rewards PRIMARY KEY (id),
    CONSTRAINT fk_referral_rewards_farmer FOREIGN KEY (farmer_id) REFERENCES farmers (id),
    CONSTRAINT fk_referral_rewards_subscription FOREIGN KEY (subscription_id) REFERENCES farmer_subscriptions (id),
    CONSTRAINT ck_referral_rewards_used CHECK (referrals_used > 0)
);
CREATE INDEX idx_referral_rewards_farmer ON referral_rewards (farmer_id);

-- Mukofot obunasi — to'lov usuli REFERRAL (summa 0)
ALTER TABLE farmer_subscriptions
    DROP CONSTRAINT ck_subscriptions_method,
    ADD CONSTRAINT ck_subscriptions_method CHECK (payment_method IN ('CASH', 'CARD', 'TRANSFER', 'OTHER', 'REFERRAL'));

