-- C4: AI maslahatchi. Fermer o'simlik rasmini yuboradi → Claude (vision) tavsiyasi → fermerga (yakuniy, "agronom bilan
-- maslahatlashing" ogohlantirishi bilan; agronom tekshiruvi YO'Q — loyiha egasi qarori). Navbat va tarix — shu jadvalda.
CREATE TABLE advisor_requests (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    farmer_id        BIGINT        NOT NULL,
    field_id         BIGINT,                              -- ixtiyoriy: qaysi dala (ekin, joy konteksti)
    photo_hash_id    VARCHAR(22)   NOT NULL,
    farmer_note      VARCHAR(1000),
    language         VARCHAR(8)    NOT NULL,
    status           VARCHAR(16)   NOT NULL DEFAULT 'PENDING',
    attempts         INT           NOT NULL DEFAULT 0,
    next_attempt_at  TIMESTAMP(6)  NOT NULL DEFAULT now(),
    ai_model         VARCHAR(80),
    ai_result        JSONB,                               -- AdvisorDiagnosis (fermer tilida)
    ai_error         VARCHAR(500),
    input_tokens     INT,
    output_tokens    INT,
    answered_at      TIMESTAMP(6),
    created_date     TIMESTAMP(6)  NOT NULL DEFAULT now(),

    CONSTRAINT pk_advisor_requests PRIMARY KEY (id),
    CONSTRAINT fk_advisor_requests_farmer FOREIGN KEY (farmer_id) REFERENCES farmers (id),
    CONSTRAINT fk_advisor_requests_field FOREIGN KEY (field_id) REFERENCES fields (id),
    CONSTRAINT fk_advisor_requests_photo FOREIGN KEY (photo_hash_id) REFERENCES files (hash_id),
    -- PENDING (navbatda) → ANSWERED | FAILED (AI javob bermadi — limitdan ayirilmaydi, fermer qayta yuboradi)
    CONSTRAINT ck_advisor_requests_status CHECK (status IN ('PENDING', 'ANSWERED', 'FAILED'))
);
CREATE INDEX idx_advisor_requests_queue ON advisor_requests (next_attempt_at) WHERE status = 'PENDING';
CREATE INDEX idx_advisor_requests_farmer ON advisor_requests (farmer_id, created_date DESC);
CREATE INDEX idx_advisor_requests_created ON advisor_requests (created_date DESC);

ALTER TABLE notifications DROP CONSTRAINT ck_notifications_category;
ALTER TABLE notifications ADD CONSTRAINT ck_notifications_category
    CHECK (category IN ('ANALYSIS', 'IRRIGATION', 'FEEDBACK', 'REFERRAL', 'BROADCAST', 'SYSTEM', 'WEATHER', 'MONITORING', 'ADVISOR'));

