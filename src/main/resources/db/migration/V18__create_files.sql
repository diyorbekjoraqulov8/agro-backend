-- Fayl servisi: fayl serverdagi papkada (app.files.dir), DB'da — metadata va papka ichidagi nisbiy yo'l.
-- Tashqariga faqat hash_id chiqadi (tasodifiy, taxmin qilib bo'lmaydi); ichki id va path — hech qachon.
CREATE TABLE files (
    id             BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    hash_id        VARCHAR(32)   NOT NULL,
    path           VARCHAR(255)  NOT NULL,          -- papkaga nisbiy: 2026/10/<hash_id>.jpg (papka ko'chsa ham buzilmaydi)
    original_name  VARCHAR(255)  NOT NULL,
    content_type   VARCHAR(100)  NOT NULL,          -- magic bytes bo'yicha aniqlangan, mijoz aytgani emas
    size_bytes     BIGINT        NOT NULL,
    sha256         VARCHAR(64)   NOT NULL,          -- yaxlitlik (hex); CHAR emas — Hibernate validate varchar kutadi
    width          INT,
    height         INT,
    source         VARCHAR(16)   NOT NULL,          -- STAFF (admin paneldan) / TELEGRAM (fermerdan)
    uploaded_by_id    BIGINT,                       -- xodim id; FK yo'q (audit kabi)
    uploaded_by_email VARCHAR(120),
    created_date   TIMESTAMP(6)  NOT NULL DEFAULT now(),

    CONSTRAINT pk_files PRIMARY KEY (id),
    CONSTRAINT uk_files_hash_id UNIQUE (hash_id),
    CONSTRAINT uk_files_path UNIQUE (path),
    CONSTRAINT ck_files_source CHECK (source IN ('STAFF', 'TELEGRAM')),
    CONSTRAINT ck_files_size CHECK (size_bytes > 0)
);

-- Xabarda rasm o'rniga fayl hash_id'si. photo_file_id (Telegram) — eski xabarlar uchun qoladi:
-- ilova ishga tushganda fonda yuklab olinib files'ga ko'chiriladi (FeedbackFileBackfill)
ALTER TABLE feedback_messages
    ADD COLUMN file_hash_id VARCHAR(32),
    ADD CONSTRAINT fk_feedback_messages_file FOREIGN KEY (file_hash_id) REFERENCES files (hash_id),
    DROP CONSTRAINT ck_feedback_messages_body,
    ADD CONSTRAINT ck_feedback_messages_body CHECK (text IS NOT NULL OR photo_file_id IS NOT NULL OR file_hash_id IS NOT NULL);

CREATE INDEX idx_feedback_messages_legacy_photo ON feedback_messages (id)
    WHERE photo_file_id IS NOT NULL AND file_hash_id IS NULL;

INSERT INTO permissions (name, description) VALUES
    ('file:read',   'Fayllarni ko''rish/yuklab olish'),
    ('file:upload', 'Fayl yuklash (chatga rasm, hujjat)')
ON CONFLICT (name) WHERE deleted = FALSE DO NOTHING;

-- Murojaatlar bilan ishlaydigan rollar
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM roles r CROSS JOIN permissions p
WHERE r.name IN ('ADMIN', 'AGRONOMIST', 'OPERATOR') AND p.name IN ('file:read', 'file:upload')
ON CONFLICT DO NOTHING;
