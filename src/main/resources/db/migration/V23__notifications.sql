    (r.name = 'ADMIN'      AND p.name IN ('notification:read', 'notification:send'))
 OR (r.name = 'MANAGER'    AND p.name IN ('notification:read', 'notification:send'))
 OR (r.name IN ('OPERATOR', 'AGRONOMIST') AND p.name = 'notification:read')
ON CONFLICT DO NOTHING;
