-- D3: Bildirishnoma servisi (outbox). Har xabar avval shu yerga (chaqiruvchi tranzaksiyasida), keyin dispatcher
-- kanalga (hozir TELEGRAM; keyin — MOBILE, WEB) yuboradi: qayta urinish, limit, jurnal, kampaniyalar.
CREATE TABLE notification_campaigns (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    title             VARCHAR(120)  NOT NULL,
    texts             JSONB         NOT NULL,            -- {"uz": "...", "ru": "...", "en": "..."} — fermer tilida, bo'sh bo'lsa uz
    button_texts      JSONB,                             -- ixtiyoriy havola tugmasi matni (tillar bo'yicha)
    button_url        VARCHAR(500),
    audience          JSONB         NOT NULL,            -- {"type": "ALL|FILTER|SINGLE", ...filtr}
    status            VARCHAR(16)   NOT NULL DEFAULT 'SCHEDULED',
    scheduled_at      TIMESTAMP(6)  NOT NULL,
    total             INT,
    created_by_email  VARCHAR(120),
    created_date      TIMESTAMP(6)  NOT NULL DEFAULT now(),
    started_at        TIMESTAMP(6),
    finished_at       TIMESTAMP(6),

    CONSTRAINT pk_notification_campaigns PRIMARY KEY (id),
    CONSTRAINT ck_notification_campaigns_status CHECK (status IN ('SCHEDULED', 'SENDING', 'DONE', 'CANCELLED')),
    CONSTRAINT ck_notification_campaigns_url CHECK (button_url IS NULL OR button_url ~ '^https://')
);
CREATE INDEX idx_notification_campaigns_due ON notification_campaigns (scheduled_at) WHERE status = 'SCHEDULED';

CREATE TABLE notifications (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    farmer_id        BIGINT        NOT NULL,
    channel          VARCHAR(16)   NOT NULL DEFAULT 'TELEGRAM',
    category         VARCHAR(24)   NOT NULL,
    template         VARCHAR(48)   NOT NULL,            -- 'text' — tayyor matn; boshqasi — kanal renderer'i (analysis.completed …)
    params           JSONB         NOT NULL DEFAULT '{}',
    preview          VARCHAR(500),                       -- jurnal uchun qisqa tavsif
    status           VARCHAR(16)   NOT NULL DEFAULT 'PENDING',
    attempts         INT           NOT NULL DEFAULT 0,
    next_attempt_at  TIMESTAMP(6)  NOT NULL DEFAULT now(),
    last_error       VARCHAR(500),
    campaign_id      BIGINT,
    ref_type         VARCHAR(32),                        -- masalan FEEDBACK_MESSAGE — yetkazilganda shu obyekt yangilanadi
    ref_id           BIGINT,
    created_date     TIMESTAMP(6)  NOT NULL DEFAULT now(),
    sent_at          TIMESTAMP(6),

    CONSTRAINT pk_notifications PRIMARY KEY (id),
    CONSTRAINT fk_notifications_farmer FOREIGN KEY (farmer_id) REFERENCES farmers (id),
    CONSTRAINT fk_notifications_campaign FOREIGN KEY (campaign_id) REFERENCES notification_campaigns (id),
    CONSTRAINT ck_notifications_status CHECK (status IN ('PENDING', 'SENDING', 'SENT', 'FAILED', 'SKIPPED', 'CANCELLED')),
    CONSTRAINT ck_notifications_channel CHECK (channel IN ('TELEGRAM', 'MOBILE', 'WEB')),
    CONSTRAINT ck_notifications_category CHECK (category IN ('ANALYSIS', 'IRRIGATION', 'FEEDBACK', 'REFERRAL', 'BROADCAST', 'SYSTEM'))
);
-- Dispatcher navbati: faqat kutayotganlar (qisman index — kichik)
CREATE INDEX idx_notifications_queue ON notifications (next_attempt_at) WHERE status = 'PENDING';
CREATE INDEX idx_notifications_sending ON notifications (next_attempt_at) WHERE status = 'SENDING';
CREATE INDEX idx_notifications_farmer ON notifications (farmer_id, created_date DESC);
CREATE INDEX idx_notifications_campaign ON notifications (campaign_id, status) WHERE campaign_id IS NOT NULL;
CREATE INDEX idx_notifications_created ON notifications (created_date DESC);

