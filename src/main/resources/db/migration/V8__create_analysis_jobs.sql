-- Navbat jadvali. Soft delete YO'Q — tarix o'chirilmaydi (audit_logs mantiqi)
CREATE TABLE analysis_jobs (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    field_id     BIGINT       NOT NULL,
    kind         VARCHAR(16)  NOT NULL DEFAULT 'FREE',
    status       VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    season_start DATE         NOT NULL,
    season_end   DATE         NOT NULL,
    attempts     INT          NOT NULL DEFAULT 0,
    next_try_at  TIMESTAMP(6) NOT NULL DEFAULT now(),
    result       JSONB,          -- rasmlar SIZ
    map_png      BYTEA,
    chart_png    BYTEA,
    error        VARCHAR(500),
    started_at   TIMESTAMP(6),
    finished_at  TIMESTAMP(6),
    created_date TIMESTAMP(6),
    updated_date TIMESTAMP(6),

    CONSTRAINT pk_analysis_jobs PRIMARY KEY (id),
    CONSTRAINT fk_analysis_field FOREIGN KEY (field_id) REFERENCES fields (id),
    CONSTRAINT ck_analysis_kind   CHECK (kind IN ('FREE', 'PAID')),
    CONSTRAINT ck_analysis_status CHECK (status IN ('PENDING', 'RUNNING', 'DONE', 'FAILED')),
    CONSTRAINT ck_analysis_season CHECK (season_start < season_end)
);

-- Worker navbati: FOR UPDATE SKIP LOCKED shu index bo'yicha
CREATE INDEX idx_analysis_queue   ON analysis_jobs (next_try_at) WHERE status = 'PENDING';
-- Ilova o'chib qolganda RUNNING'da qotgan job'larni qaytarish uchun
CREATE INDEX idx_analysis_running ON analysis_jobs (started_at)  WHERE status = 'RUNNING';
CREATE INDEX idx_analysis_field   ON analysis_jobs (field_id, created_date DESC);
