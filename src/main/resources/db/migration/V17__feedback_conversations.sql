-- Fermerda bitta ochiq suhbat: eskilari (eng yangisidan tashqari) tizim tomonidan yopiladi
UPDATE feedback f SET status = 'CLOSED', closed_at = now(), closed_by = 'SYSTEM', unread_staff = 0
WHERE f.status = 'NEW'
  AND EXISTS (SELECT 1 FROM feedback n WHERE n.farmer_id = f.farmer_id AND n.status = 'NEW' AND n.id > f.id);

