-- Murojaat → suhbat (chat). Fermer ↔ operator yozishmasi ikki tomondan biri yakunlaguncha davom etadi.
--   NEW    — operator hali olmagan (navbat)
--   OPEN   — operator oldi (assignee), yozishma davom etmoqda; boshqa operator ololmaydi
--   CLOSED — yakunlangan (fermer, xodim yoki tizim); fermer operatorni 1–5 baholashi mumkin
-- Xabarlar — feedback_messages. Eski bitta-javob ustunlari xabarlarga ko'chiriladi va o'chiriladi.

CREATE TABLE feedback_messages (
    id             BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    feedback_id    BIGINT        NOT NULL,
    sender         VARCHAR(8)    NOT NULL,
    staff_id       BIGINT,                    -- FK yo'q (audit_logs kabi: xodim o'chsa ham tarix buzilmasin)
    staff_email    VARCHAR(120),
    text           TEXT,
    photo_file_id  VARCHAR(256),              -- Telegram file_id; fayl Telegram'da qoladi
    delivered      BOOLEAN,                   -- faqat STAFF: FALSE — fermer botni bloklagan / tarmoq
    created_date   TIMESTAMP(6)  NOT NULL DEFAULT now(),

    CONSTRAINT pk_feedback_messages PRIMARY KEY (id),
    CONSTRAINT fk_feedback_messages_feedback FOREIGN KEY (feedback_id) REFERENCES feedback (id),
    CONSTRAINT ck_feedback_messages_sender CHECK (sender IN ('FARMER', 'STAFF', 'SYSTEM')),
    CONSTRAINT ck_feedback_messages_body   CHECK (text IS NOT NULL OR photo_file_id IS NOT NULL),
    CONSTRAINT ck_feedback_messages_text   CHECK (text IS NULL OR length(text) BETWEEN 1 AND 4000)
);
CREATE INDEX idx_feedback_messages_thread ON feedback_messages (feedback_id, id);

ALTER TABLE feedback
    ADD COLUMN subject          VARCHAR(200),
    ADD COLUMN assignee_id      BIGINT,
    ADD COLUMN assignee_email   VARCHAR(120),
    ADD COLUMN assigned_at      TIMESTAMP(6),
    ADD COLUMN last_message_at  TIMESTAMP(6),
    ADD COLUMN last_sender      VARCHAR(8),
