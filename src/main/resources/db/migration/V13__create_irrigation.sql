-- Sug'orish eslatmasi: dala bo'yicha holat (1:1). Hisob stateless (Python har safar oxirgi
-- sug'orishdan qayta hisoblaydi) — bu yerda faqat kirish parametrlari va oxirgi natija keshi.
CREATE TABLE field_water (
    field_id            BIGINT       NOT NULL,
    soil_type           VARCHAR(8),               -- fermer javobi; NULL — "bilmayman" (auto ishlatiladi)
    soil_type_auto      VARCHAR(8),               -- SoilGrids (ISRIC) — fermer javobini tekshirish uchun
    sand_pct            NUMERIC(5,1),
    clay_pct            NUMERIC(5,1),
    last_irrigated_on   DATE,
    reminders_enabled   BOOLEAN      NOT NULL DEFAULT TRUE,
    ndvi                NUMERIC(4,3),             -- Kc uchun; har hafta yangilanadi
    ndvi_on             DATE,
    timezone            VARCHAR(64),
    utc_offset_seconds  INT,                      -- dala mahalliy vaqti — eslatma ertalab 7 da
    next_irrigation_on  DATE,
    depletion_pct       NUMERIC(6,1),             -- RAW'ga nisbatan, %
    computed_at         TIMESTAMP(6),
    last_reminder_on    DATE,
    last_reminder_kind  VARCHAR(16),
    created_date        TIMESTAMP(6),
    updated_date        TIMESTAMP(6),

    CONSTRAINT pk_field_water PRIMARY KEY (field_id),
    CONSTRAINT fk_field_water_field FOREIGN KEY (field_id) REFERENCES fields (id),
    CONSTRAINT ck_field_water_soil      CHECK (soil_type IS NULL OR soil_type IN ('SAND', 'LOAM', 'CLAY')),
    CONSTRAINT ck_field_water_soil_auto CHECK (soil_type_auto IS NULL OR soil_type_auto IN ('SAND', 'LOAM', 'CLAY')),
    CONSTRAINT ck_field_water_kind      CHECK (last_reminder_kind IS NULL OR last_reminder_kind IN ('DUE', 'SOON', 'STATUS'))
);

-- Eslatma navbati: faqat yoqilgan va sozlangan dalalar
CREATE INDEX idx_field_water_active ON field_water (field_id)
    WHERE reminders_enabled = TRUE AND last_irrigated_on IS NOT NULL;

-- Sug'orish tarixi (o'chirilmaydi) — admin panel va keyin modelni sozlash uchun
CREATE TABLE irrigation_events (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    field_id      BIGINT       NOT NULL,
    irrigated_on  DATE         NOT NULL,
    source        VARCHAR(16)  NOT NULL,
    created_date  TIMESTAMP(6) NOT NULL DEFAULT now(),

    CONSTRAINT pk_irrigation_events PRIMARY KEY (id),
    CONSTRAINT fk_irrigation_events_field FOREIGN KEY (field_id) REFERENCES fields (id),
    CONSTRAINT ck_irrigation_events_source CHECK (source IN ('FARMER', 'SETUP', 'STAFF'))
);

CREATE INDEX idx_irrigation_events_field ON irrigation_events (field_id, irrigated_on DESC);
