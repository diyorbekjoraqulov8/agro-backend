-- L2: aniqlik — "aslida nima bor edi" (ground truth) va tizim xulosalariga xodim bahosi.
-- Kuzatuv: admin dalada ko'rgani. lat/lon NULL — butun dala.
CREATE TABLE field_observations (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    field_id      BIGINT        NOT NULL,
    observed_on   DATE          NOT NULL,
    condition     VARCHAR(16)   NOT NULL,
    cause         VARCHAR(16),
    lat           NUMERIC(9, 6),
    lon           NUMERIC(9, 6),
    note          VARCHAR(1000),
    author_email  VARCHAR(255),
    deleted       BOOLEAN       NOT NULL DEFAULT FALSE,
    created_date  TIMESTAMP(6),
    updated_date  TIMESTAMP(6),

    CONSTRAINT pk_field_observations PRIMARY KEY (id),
    CONSTRAINT fk_field_observations_field FOREIGN KEY (field_id) REFERENCES fields (id),
    CONSTRAINT ck_field_observations_condition CHECK (condition IN ('GOOD', 'WEAK', 'DAMAGED', 'BARE', 'HARVESTED')),
    CONSTRAINT ck_field_observations_cause CHECK (cause IS NULL OR cause IN
        ('WATER', 'NUTRIENT', 'DISEASE', 'PEST', 'WEEDS', 'SALINITY', 'LODGING', 'HAIL', 'OTHER', 'UNKNOWN')),
    CONSTRAINT ck_field_observations_point CHECK ((lat IS NULL) = (lon IS NULL))
);
CREATE INDEX idx_field_observations_field ON field_observations (field_id, observed_on) WHERE deleted = FALSE;

-- Baho: har xulosaga bitta (qayta baholash — ustiga yoziladi). Soft delete yo'q — oddiy UNIQUE yetarli
CREATE TABLE finding_reviews (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    target_type     VARCHAR(16)   NOT NULL,
    target_id       BIGINT        NOT NULL,
    field_id        BIGINT        NOT NULL,
    verdict         VARCHAR(16)   NOT NULL,
    note            VARCHAR(1000),
    reviewer_email  VARCHAR(255),
    created_date    TIMESTAMP(6),
    updated_date    TIMESTAMP(6),

    CONSTRAINT pk_finding_reviews PRIMARY KEY (id),
    CONSTRAINT fk_finding_reviews_field FOREIGN KEY (field_id) REFERENCES fields (id),
    CONSTRAINT uk_finding_reviews_target UNIQUE (target_type, target_id),
    CONSTRAINT ck_finding_reviews_type CHECK (target_type IN ('ANALYSIS', 'MONITORING')),
    CONSTRAINT ck_finding_reviews_verdict CHECK (verdict IN ('CORRECT', 'PARTIAL', 'WRONG'))
);
CREATE INDEX idx_finding_reviews_field ON finding_reviews (field_id);
