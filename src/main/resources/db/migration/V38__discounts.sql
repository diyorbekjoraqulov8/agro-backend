-- Chegirmalar: admin yaratadi; fermerga mos kelganlarning eng foydalisi qo'llanadi (qo'shilmaydi).
-- audiences — kimlarga (vergul bilan): FREE (hech to'lamagan/bepul), TRIAL (Pro sinovida), PAID (faol obuna), EXPIRED (obunasi tugagan)
-- plan_ids — qaysi tariflarga (vergul bilan id'lar); bo'sh — barcha narxli tariflar
CREATE TABLE discounts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name             VARCHAR(100)  NOT NULL,
    kind             VARCHAR(16)   NOT NULL,
    value_type       VARCHAR(8)    NOT NULL,
    value            NUMERIC(12, 2) NOT NULL,
    audiences        VARCHAR(64)   NOT NULL,
    plan_ids         VARCHAR(255)  NOT NULL DEFAULT '',
    starts_on        DATE          NOT NULL,
    ends_on          DATE,
    active           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_date     TIMESTAMP(6),
    updated_date     TIMESTAMP(6),
    updated_by_email VARCHAR(120),
    CONSTRAINT pk_discounts PRIMARY KEY (id),
    CONSTRAINT ck_discounts_kind CHECK (kind IN ('SEASONAL', 'PROMO', 'FIRST_PAYMENT', 'LOYALTY')),
    CONSTRAINT ck_discounts_value_type CHECK (value_type IN ('PERCENT', 'FIXED')),
    CONSTRAINT ck_discounts_value CHECK (value > 0 AND (value_type <> 'PERCENT' OR value <= 90)),
    CONSTRAINT ck_discounts_period CHECK (ends_on IS NULL OR ends_on >= starts_on),
    CONSTRAINT ck_discounts_audiences CHECK (audiences ~ '^(FREE|TRIAL|PAID|EXPIRED)(,(FREE|TRIAL|PAID|EXPIRED))*$'),
    CONSTRAINT ck_discounts_plans CHECK (plan_ids ~ '^([0-9]+(,[0-9]+)*)?$')
);
CREATE INDEX idx_discounts_active ON discounts (starts_on, ends_on) WHERE active = TRUE;

