-- C3: Avtomatik monitoring — har yangi Sentinel-2 surati chiqqanda dala oldingi ochiq surat bilan solishtiriladi.
-- field_monitoring — navbat (qaysi dala qachon tekshiriladi, oxirgi ko'rilgan surat); monitoring_events — tarix.
CREATE TABLE field_monitoring (
    field_id         BIGINT        NOT NULL,
    last_scene_date  DATE,                                -- Python'ga "since": shundan keyingi surat — yangi
    last_ndvi        NUMERIC(5,3),
    next_check_at    TIMESTAMP(6)  NOT NULL DEFAULT now(),
    last_checked_at  TIMESTAMP(6),
    failures         INT           NOT NULL DEFAULT 0,    -- ketma-ket xatolar (admin ko'rsin; oshib ketsa — kamroq urinish)

    CONSTRAINT pk_field_monitoring PRIMARY KEY (field_id),
    CONSTRAINT fk_field_monitoring_field FOREIGN KEY (field_id) REFERENCES fields (id)
);
CREATE INDEX idx_field_monitoring_due ON field_monitoring (next_check_at);

CREATE TABLE monitoring_events (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    field_id          BIGINT        NOT NULL,
    scene_date        DATE          NOT NULL,
    ref_date          DATE,                               -- null — solishtiradigan surat yo'q edi (faqat holat)
    ndvi              NUMERIC(5,3)  NOT NULL,
    ndvi_ref          NUMERIC(5,3),
    decline_pct       NUMERIC(5,1),
    decline_side      VARCHAR(8),
    improve_pct       NUMERIC(5,1),
    verdict           VARCHAR(16)   NOT NULL,             -- DECLINE (xabar ketdi) | STABLE | HARVEST | NO_CROP | BASELINE
    map_file_hash_id  VARCHAR(22),                        -- o'zgarish xaritasi (files, source=SYSTEM)
    created_date      TIMESTAMP(6)  NOT NULL DEFAULT now(),

    CONSTRAINT pk_monitoring_events PRIMARY KEY (id),
    CONSTRAINT fk_monitoring_events_field FOREIGN KEY (field_id) REFERENCES fields (id),
    CONSTRAINT uk_monitoring_events UNIQUE (field_id, scene_date),
    CONSTRAINT ck_monitoring_events_verdict CHECK (verdict IN ('DECLINE', 'STABLE', 'HARVEST', 'NO_CROP', 'BASELINE'))
);
CREATE INDEX idx_monitoring_events_created ON monitoring_events (created_date DESC);

ALTER TABLE notifications DROP CONSTRAINT ck_notifications_category;
ALTER TABLE notifications ADD CONSTRAINT ck_notifications_category
    CHECK (category IN ('ANALYSIS', 'IRRIGATION', 'FEEDBACK', 'REFERRAL', 'BROADCAST', 'SYSTEM', 'WEATHER', 'MONITORING'));
