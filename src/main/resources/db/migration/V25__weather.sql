-- C2: Ob-havo xavfi ogohlantirishi. Prognoz — dala emas, KATAK bo'yicha (0.1° ≈ 10 km): bir qishloqdagi
-- yuzlab dala — bitta Open-Meteo so'rovi. Job har soat eskirgan kataklarni yangilaydi (≥ 3 soat).
CREATE TABLE weather_forecasts (
    cell_key            VARCHAR(24)   NOT NULL,            -- "41.3:69.2" (lat:lon, 0.1° ga yaxlitlangan)
    lat                 NUMERIC(6,3)  NOT NULL,
    lon                 NUMERIC(7,3)  NOT NULL,
    timezone            VARCHAR(64),
    utc_offset_seconds  INT,
    days                JSONB         NOT NULL,            -- [{date, tMin, tMax, gustMs, rainMm, code}] — 5 kun
    fetched_at          TIMESTAMP(6)  NOT NULL,

    CONSTRAINT pk_weather_forecasts PRIMARY KEY (cell_key)
);

-- Yuborilgan ogohlantirishlar: takrorni oldini olish (har soatlik tekshiruv bir xavfni qayta yubormasin)
-- va kuchayishni aniqlash (WARNING → DANGER — bir marta yangilangan xabar).
CREATE TABLE weather_alerts (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    farmer_id     BIGINT        NOT NULL,
    cell_key      VARCHAR(24)   NOT NULL,
    kind          VARCHAR(16)   NOT NULL,
    level         VARCHAR(16)   NOT NULL,
    event_date    DATE          NOT NULL,
    value         NUMERIC(6,1)  NOT NULL,                 -- °C, m/s yoki mm — xabardagi raqam
    created_date  TIMESTAMP(6)  NOT NULL DEFAULT now(),
    updated_date  TIMESTAMP(6),

    CONSTRAINT pk_weather_alerts PRIMARY KEY (id),
    CONSTRAINT fk_weather_alerts_farmer FOREIGN KEY (farmer_id) REFERENCES farmers (id),
    CONSTRAINT uk_weather_alerts UNIQUE (farmer_id, cell_key, kind, event_date),
    CONSTRAINT ck_weather_alerts_kind CHECK (kind IN ('FROST', 'HEAT', 'WIND', 'RAIN')),
    CONSTRAINT ck_weather_alerts_level CHECK (level IN ('WARNING', 'DANGER'))
);
CREATE INDEX idx_weather_alerts_recent ON weather_alerts (farmer_id, kind, event_date DESC);

