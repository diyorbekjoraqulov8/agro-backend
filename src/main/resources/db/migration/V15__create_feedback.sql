-- Fermer murojaatlari (bot → "💬 Fikr va yordam"): muammo, taklif, savol.
-- O'chirilmaydi — CLOSED (spam, takror). Javob bot orqali fermerga yuboriladi.
-- replied_by_id — xodim id, FK yo'q (audit_logs kabi: xodim o'chsa ham tarix buzilmasin)
CREATE TABLE feedback (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    farmer_id          BIGINT        NOT NULL,
    kind               VARCHAR(16)   NOT NULL,
    message            TEXT          NOT NULL,
    photo_file_id      VARCHAR(256),             -- Telegram file_id (skrinshot); fayl Telegram'da qoladi
    status             VARCHAR(16)   NOT NULL DEFAULT 'NEW',
    reply              TEXT,
    reply_delivered    BOOLEAN,                  -- NULL — javob yo'q; FALSE — fermer botni bloklagan
    replied_at         TIMESTAMP(6),
    replied_by_id      BIGINT,
    replied_by_email   VARCHAR(120),
    created_date       TIMESTAMP(6),
    updated_date       TIMESTAMP(6),

    CONSTRAINT pk_feedback PRIMARY KEY (id),
    CONSTRAINT fk_feedback_farmer FOREIGN KEY (farmer_id) REFERENCES farmers (id),
    CONSTRAINT ck_feedback_kind   CHECK (kind IN ('PROBLEM', 'SUGGESTION', 'QUESTION')),
    CONSTRAINT ck_feedback_status CHECK (status IN ('NEW', 'ANSWERED', 'CLOSED')),
    CONSTRAINT ck_feedback_message CHECK (length(message) BETWEEN 1 AND 4000)
);

CREATE INDEX idx_feedback_status ON feedback (status, created_date DESC);
CREATE INDEX idx_feedback_farmer ON feedback (farmer_id, created_date DESC);

INSERT INTO permissions (name, description) VALUES
    ('feedback:read',  'Fermer murojaatlarini ko''rish'),
    ('feedback:reply', 'Murojaatga javob berish va yopish')
ON CONFLICT (name) WHERE deleted = FALSE DO NOTHING;

-- Agronom ham javob beradi: savollarning ko'pi agronomik
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM roles r CROSS JOIN permissions p
WHERE r.name IN ('ADMIN', 'AGRONOMIST') AND p.name IN ('feedback:read', 'feedback:reply');
