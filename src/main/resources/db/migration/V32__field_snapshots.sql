CREATE TABLE field_snapshots (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    field_id          BIGINT        NOT NULL,
    scene_date        DATE          NOT NULL,
    file_hash_id      VARCHAR(32)   NOT NULL,
    ndvi              NUMERIC(5,3)  NOT NULL,
    weak_pct          NUMERIC(5,1)  NOT NULL,
    weak_lat          NUMERIC(9,6),
    weak_lon          NUMERIC(9,6),
    telegram_file_id  VARCHAR(255),                       -- qayta yuborishda rasm qayta yuklanmaydi
    created_date      TIMESTAMP(6)  NOT NULL DEFAULT now(),

    CONSTRAINT pk_field_snapshots PRIMARY KEY (id),
    CONSTRAINT fk_field_snapshots_field FOREIGN KEY (field_id) REFERENCES fields (id),
    CONSTRAINT fk_field_snapshots_file FOREIGN KEY (file_hash_id) REFERENCES files (hash_id)
);
CREATE INDEX idx_field_snapshots_field ON field_snapshots (field_id, created_date DESC);
